export function groupOf(key: EmailKey): EmailGroup {
  if (key === "reminder" || key === "reminder1h") return "meeting";
  if (key === "cancelled" || key === "noshow") return "recovery";
  if (key.startsWith("post")) return "after";
  return "content";
}
